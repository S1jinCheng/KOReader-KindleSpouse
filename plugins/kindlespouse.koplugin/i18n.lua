function I18n.T(key, ...)
    local semantic = I18n.keys[key] or key
    local language = G_reader_settings and G_reader_settings:readSetting("language", "en") or "en"
    local dictionary = tostring(language):lower():sub(1, 2) == "zh" and I18n.zh or I18n.en
    local text = dictionary[semantic] or I18n.en[semantic] or key
    local count = select("#", ...)
    if count == 0 then return text end
    local arguments = { ... }
    if text:find("%%[1-9]%d*") then
        return (text:gsub("%%([1-9]%d*)", function(index)
            local value = arguments[tonumber(index)]
            return value ~= nil and tostring(value) or "%" .. index
        end))
    end
    return string.format(text, ...)
end

